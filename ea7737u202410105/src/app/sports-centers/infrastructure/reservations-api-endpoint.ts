import {BaseApiEndpoint} from '../../shared/infrastructure/base-api-endpoint';
import {Reservation} from '../domain/model/reservation.entity';
import {ReservationResource, ReservationsResponse} from './reservations-response';
import {ReservationAssembler} from './reservation-assembler';
import {HttpClient} from '@angular/common/http';
import {catchError, map, Observable} from 'rxjs';
import {environment} from '../../../environments/environment';

/**
 * Endpoint client for reservation operations.
 */
export class ReservationsApiEndpoint extends BaseApiEndpoint<Reservation, ReservationResource, ReservationsResponse, ReservationAssembler> {
  /**
   * Creates an instance of ReservationsApiEndpoint.
   * @param http - The HttpClient to be used for making API requests.
   */
  constructor(http: HttpClient) {
    super(http,
      `${environment.platformProviderApiBaseUrl}${environment.platformProviderReservationsEndpointPath}`,
      new ReservationAssembler());
  }

  /**
   * Creates a reservation sending a request without identifier, so it is generated by the backend.
   * @param entity - Reservation to persist.
   * @returns Stream with the created reservation returned by the API.
   */
  override create(entity: Reservation): Observable<Reservation> {
    const request = this.assembler.toRequestFromEntity(entity);
    return this.http.post<ReservationResource>(this.endpointUrl, request).pipe(
      map(created => this.assembler.toEntityFromResource(created)),
      catchError(this.handleError('Failed to create reservation'))
    );
  }
}
